const RECENT_KEY = "voxsy-emoji-recent";

/** Recently used emojis, newest first. */
export function recentEmojis() {
  try {
    const raw = JSON.parse(localStorage.getItem(RECENT_KEY) || "[]");
    return Array.isArray(raw) ? raw.filter((x) => typeof x === "string").slice(0, 40) : [];
  } catch {
    return [];
  }
}

export function rememberEmoji(emoji) {
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify([emoji, ...recentEmojis().filter((e) => e !== emoji)].slice(0, 40)));
  } catch {
    /* not remembered */
  }
}

